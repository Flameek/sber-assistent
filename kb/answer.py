"""Оформление найденного ответа: заголовок, шаги, источник и ответственный.

Ничего не придумывает и не переписывает: только раскладывает текст утверждённой
инструкции на шаги и добавляет поля самой инструкции (название, версию, контакт).
"""
import re

# Конец предложения: точка, «!» или «?», затем пробел и заглавная буква (или открывающая кавычка).
SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[А-ЯЁA-Z«])")


def steps(text):
    """Разбивает текст инструкции на предложения — по одному шагу на предложение."""
    return [part.strip() for part in SENTENCE_END.split(text.strip()) if part.strip()]


def as_markdown(result):
    """Текст ответа для показа: шаги нумерованным списком, если их больше одного."""
    items = steps(result["text"])
    if len(items) == 1:
        return items[0]
    return "\n".join(f"{number}. {item}" for number, item in enumerate(items, start=1))